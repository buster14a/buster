static u64 rng_state = 0x9e3779b97f4a7c15ull;
static u32 rng(void)
{
    rng_state ^= rng_state << 13;
    rng_state ^= rng_state >> 7;
    rng_state ^= rng_state << 17;
    return (u32)(rng_state >> 32);
}
static double unit(void) { return (double)rng() / 4294967296.0; }

static Event* events;
static u64 event_count;
static u32* body_event_end;
static u8* arena;
#define TYPE_COUNT 150000u

static u64 now_ns(void)
{
    struct timespec t;
    clock_gettime(CLOCK_MONOTONIC, &t);
    return (u64)t.tv_sec * 1000000000ull + (u64)t.tv_nsec;
}

static u32 key_end(u32 slot) { return slot + 1 + (slot * 7u) % 13u; }

// Builds one deterministic event stream and records its expected outcomes
// by simulating the memo's key state.
static void generate(double hit_given_populated, double publish_after_miss, double publishable, u64 expected[3], u64* publications)
{
    u64 step_total = LONG_STEP_WEIGHT;
    for (u32 i = 0; i < 64; i += 1) step_total += step_weights[i];
    u64 slot_total = 0;
    for (u32 b = 0; b < BODY_COUNT; b += 1) slot_total += bodies[b];
    u64 capacity = slot_total * 3 + BODY_COUNT * 4;
    events = malloc(capacity * sizeof(Event));
    body_event_end = malloc(BODY_COUNT * sizeof(u32));
    u32* truth_end = malloc(65536 * 4 * sizeof(u32));
    u8* truth_flags = malloc(65536 * 4);
    event_count = 0;
    for (u32 b = 0; b < BODY_COUNT; b += 1)
    {
        u32 t = bodies[b];
        memset(truth_flags, 0, t);
        u32 probes = (u32)(t * 1.0390 + unit());
        if (!probes) probes = 1;
        u32 pos = rng() % t;
        for (u32 p = 0; p < probes; p += 1)
        {
            if (p)
            {
                if (unit() < 0.090 && pos) pos = rng() % (pos + 1);
                else
                {
                    u64 r = ((u64)rng() * step_total) >> 32;
                    u32 step = 0;
                    while (step < 64 && r >= step_weights[step]) { r -= step_weights[step]; step += 1; }
                    if (step == 64) step = 64 + rng() % 448;
                    pos += step;
                    if (pos >= t) pos = rng() % t;
                }
            }
            u32 mode = VALID | RUNTIME;
            u32 end = key_end(pos);
            u8 outcome = 0;
            if (truth_flags[pos])
            {
                // Same start, possibly another end or mode: the hit share
                // among populated probes is measured, not derived.
                end = truth_end[pos];
                mode = truth_flags[pos];
                if (unit() < hit_given_populated) outcome = 1;
                else
                {
                    outcome = 2;
                    if (unit() < 0.61) mode ^= CONSTANT; else end += 1 + rng() % 7;
                }
            }
            events[event_count++] = (Event){.slot = pos, .end = end, .kind = 0, .flags = (u8)mode, .outcome = outcome, .type = pos % TYPE_COUNT};
            expected[outcome] += 1;
            // Whether a start ever publishes is a property of the start
            // (speculative and failing queries never do), not of the probe.
            u32 hash = pos * 2654435761u ^ b * 40503u;
            bool can_publish = (double)(hash >> 8) / 16777216.0 < publishable;
            if (outcome != 1 && can_publish && unit() < publish_after_miss)
            {
                events[event_count++] = (Event){.slot = pos, .end = end, .kind = 1, .flags = (u8)mode, .type = pos % TYPE_COUNT};
                truth_end[pos] = end;
                truth_flags[pos] = (u8)mode;
                *publications += 1;
            }
        }
        body_event_end[b] = (u32)event_count;
    }
    free(truth_end);
    free(truth_flags);
}

// The cold scenario evicts the body's whole scratch span (memo, skipped[],
// body_scopes[]; the larger current layout's extent) before the body starts,
// the same work for both layouts, standing in for the rest of the compiler
// having used the cache since this scratch memory was last touched.
static void flush_span(u32 t)
{
    u64 bytes = (u64)t * (sizeof(RecordA) + 1 + 4) + 64;
    for (u64 i = 0; i < bytes; i += 64) _mm_clflush(arena + i);
    _mm_mfence();
}

static int mode_ok(u32 stored, u32 flags)
{
    return (stored & ~(CHECKED | NONPLACE)) == (flags & ~CHECKED) && (stored & flags) == flags;
}

// Per body, the memo table(s) come first in the rewound scratch arena,
// followed by the skipped[] byte column and the body_scopes[] index the
// validator allocates next, exactly as both layouts do in c_parse.c.
static u64 replay_a(int cold, u64 outcome_count[3])
{
    u64 begin = now_ns();
    u64 e = 0;
    for (u32 b = 0; b < BODY_COUNT; b += 1)
    {
        u32 t = bodies[b];
        if (cold) flush_span(t);
        RecordA* table = (RecordA*)arena;
        memset(table, 0, (u64)t * sizeof(RecordA));
        u8* skipped = (u8*)(table + t);
        memset(skipped, 0, t);
        u32* scopes = (u32*)(((uintptr_t)(skipped + t) + 3) & ~(uintptr_t)3);
        for (u32 i = 0; i < t; i += 1) scopes[i] = i >> 4;
        for (; e < body_event_end[b]; e += 1)
        {
            Event ev = events[e];
            RecordA* q = table + ev.slot;
            if (ev.kind == 0)
            {
                u32 hit = q->end == ev.end && q->scope == scopes[ev.slot] && mode_ok(q->flags, ev.flags) && q->type < TYPE_COUNT;
                outcome_count[hit ? 1 : (q->flags ? 2 : 0)] += 1;
            }
            else
            {
                *q = (RecordA){.end = ev.end, .scope = scopes[ev.slot], .type = ev.type, .flags = ev.flags};
            }
        }
    }
    return now_ns() - begin;
}

static u64 replay_b(int cold, u64 outcome_count[3])
{
    u64 begin = now_ns();
    u64 e = 0;
    for (u32 b = 0; b < BODY_COUNT; b += 1)
    {
        u32 t = bodies[b];
        if (cold) flush_span(t);
        PayloadB* payload = (PayloadB*)arena;
        u8* flags = (u8*)(payload + t);
        memset(flags, 0, t);
        u8* skipped = flags + t;
        memset(skipped, 0, t);
        u32* scopes = (u32*)(((uintptr_t)(skipped + t) + 3) & ~(uintptr_t)3);
        for (u32 i = 0; i < t; i += 1) scopes[i] = i >> 4;
        for (; e < body_event_end[b]; e += 1)
        {
            Event ev = events[e];
            if (ev.kind == 0)
            {
                u32 stored = flags[ev.slot];
                u32 hit = mode_ok(stored, ev.flags);
                if (hit)
                {
                    PayloadB const* q = payload + ev.slot;
                    hit = q->end == ev.end && q->scope == scopes[ev.slot] && q->type < TYPE_COUNT;
                }
                outcome_count[hit ? 1 : (stored ? 2 : 0)] += 1;
            }
            else
            {
                payload[ev.slot] = (PayloadB){.end = ev.end, .scope = scopes[ev.slot], .type = ev.type};
                flags[ev.slot] = ev.flags;
            }
        }
    }
    return now_ns() - begin;
}

static int compare_u64(void const* a, void const* b)
{
    u64 x = *(u64 const*)a, y = *(u64 const*)b;
    return x < y ? -1 : x > y;
}

