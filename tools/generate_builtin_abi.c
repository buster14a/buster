static void recompute(AbiTable* abi, const TypeTable* table)
{
    memset(abi->rows, 0, BUSTER_TYPE_BUILTIN_COUNT * BUSTER_ABI_ROW_BYTES);
    memset(abi->pass, 0, BUSTER_TYPE_BUILTIN_COUNT * sizeof(*abi->pass));
    memset(abi->stack_bytes, 0, BUSTER_TYPE_BUILTIN_COUNT * sizeof(*abi->stack_bytes));
    memset(abi->alignment_log2, 0, BUSTER_TYPE_BUILTIN_COUNT);
    memset(abi->storage, 0, BUSTER_TYPE_BUILTIN_COUNT);
    memset(abi->layout, 0, BUSTER_TYPE_BUILTIN_COUNT * sizeof(*abi->layout));
    memset(abi->results, 0, BUSTER_TYPE_BUILTIN_COUNT * sizeof(*abi->results));
    abi->larger = 0;
    abi->rare = 0;
    for (uint32_t a = 0; a < BUSTER_ABI_CLASS_COUNT; a += 1)
    {
        for (uint32_t b = 0; b < BUSTER_ABI_CLASS_COUNT; b += 1)
        {
            abi->merge[a * BUSTER_ABI_CLASS_COUNT + b] = abi_merge_class((uint8_t)a, (uint8_t)b);
        }
    }
    for (uint32_t i = 1; i < BUSTER_TYPE_BUILTIN_COUNT; i += 1)
    {
        if (table->types.kind[i] != BUSTER_TYPE_KIND_NONE)
        {
            abi_store_row(abi, i, abi_simple_row(abi_simple(abi, table, i)));
            abi_finish(abi, table, i);
        }
    }
}

static void bytes(const char* name, const uint8_t* values, uint32_t count, uint32_t width)
{
    printf("    .%s =\n", name);
    for (uint32_t first = 0; first < count; first += width)
    {
        fputs("        \"", stdout);
        for (uint32_t at = first; at < count && at < first + width; at += 1)
        {
            printf("\\x%02x", values[at]);
        }
        printf("\" // %u\n", first / width);
    }
    fputs("    ,\n", stdout);
}

static void words(const char* name, const uint32_t* values)
{
    printf("    .%s = {\n", name);
    for (uint32_t i = 0; i < BUSTER_TYPE_BUILTIN_COUNT; i += 1)
    {
        printf("        0x%08" PRIx32 ", // %u\n", values[i], i);
    }
    fputs("    },\n", stdout);
}

int main(void)
{
    const TypeCapacity capacity = { .types = 0, .parameters = 0, .tags = 0, .members = 0 };
    Arena arena = arena_reserve(type_capacity_bytes(capacity));
    Arena index = arena_reserve(type_index_capacity_bytes(capacity));
    Arena rows = arena_reserve(abi_capacity_bytes(BUSTER_TYPE_BUILTIN_COUNT));
    TypeTable table = { 0 };
    AbiTable abi = { 0 };
    bool valid = type_initialize(&table, &arena, &index, capacity) &&
                 abi_initialize_types(&abi, &rows, &table, 16, BUSTER_TYPE_BUILTIN_COUNT);
    if (valid)
    {
        recompute(&abi, &table);
        fputs("// SPDX-License-Identifier: Apache-2.0 WITH LLVM-exception\n// Copyright (c) 2026 David Gonzalez Martin. Original generated builtin ABI facts.\n// Generated by tools/generate_builtin_abi.c from c_types.c and calling_convention.c.\n// Regenerate after changing builtin type facts or classification; independent tests recompute all fields.\n\ntypedef struct AbiBuiltinRows AbiBuiltinRows;\nstruct AbiBuiltinRows\n{\n    uint8_t rows[BUSTER_TYPE_BUILTIN_COUNT * BUSTER_ABI_ROW_BYTES];\n    uint32_t pass[BUSTER_TYPE_BUILTIN_COUNT];\n    uint32_t stack_bytes[BUSTER_TYPE_BUILTIN_COUNT];\n    uint8_t alignment_log2[BUSTER_TYPE_BUILTIN_COUNT];\n    uint8_t storage[BUSTER_TYPE_BUILTIN_COUNT];\n    uint64_t layout[BUSTER_TYPE_BUILTIN_COUNT];\n    AbiReturn results[BUSTER_TYPE_BUILTIN_COUNT];\n    uint8_t merge[BUSTER_ABI_CLASS_COUNT * BUSTER_ABI_CLASS_COUNT];\n};\n\n_Alignas(64) static const AbiBuiltinRows abi_builtin_rows = {\n", stdout);
        bytes("rows", abi.rows, BUSTER_TYPE_BUILTIN_COUNT * BUSTER_ABI_ROW_BYTES, BUSTER_ABI_ROW_BYTES);
        words("pass", abi.pass);
        words("stack_bytes", abi.stack_bytes);
        bytes("alignment_log2", abi.alignment_log2, BUSTER_TYPE_BUILTIN_COUNT, 16);
        bytes("storage", abi.storage, BUSTER_TYPE_BUILTIN_COUNT, 16);
        fputs("    .layout = {\n", stdout);
        for (uint32_t i = 0; i < BUSTER_TYPE_BUILTIN_COUNT; i += 1)
        {
            printf("        UINT64_C(0x%016" PRIx64 "), // %u\n", abi.layout[i], i);
        }
        fputs("    },\n    .results = {\n", stdout);
        for (uint32_t i = 0; i < BUSTER_TYPE_BUILTIN_COUNT; i += 1)
        {
            const AbiReturn r = abi.results[i];
            printf("        { // %u\n            .kind = %u,\n            .flags = %u,\n            .part_bytes = %u,\n            .registers = {\n", i, r.kind, r.flags, r.part_bytes);
            for (uint32_t n = 0; n < BUSTER_ABI_RESULT_PARTS; n += 1)
            {
                printf("                %u,\n", r.registers[n]);
            }
            printf("            },\n            .padding = %u,\n        },\n", r.padding);
        }
        fputs("    },\n", stdout);
        bytes("merge", abi.merge, BUSTER_ABI_CLASS_COUNT * BUSTER_ABI_CLASS_COUNT, 8);
        fputs("};\n", stdout);
        valid = fflush(stdout) == 0 && !ferror(stdout) && abi.larger == 0 && abi.rare == 0;
    }
    arena_release(&rows);
    arena_release(&index);
    arena_release(&arena);
    return valid ? 0 : 1;
}
