static char8 const compiler_driver_wasi_main_source[] =
    "#if !defined(__wasi__) || !defined(__wasip1__)\n"
    "#error \"missing WASI target macros\"\n"
    "#endif\n"
    "#if !defined(__wasm__) || !defined(__wasm32__) || !defined(__ILP32__) || !defined(_ILP32)\n"
    "#error \"missing wasm32 ILP32 target macros\"\n"
    "#endif\n"
    "#if defined(__wasm64__) || defined(__LP64__) || defined(_LP64)\n"
    "#error \"wasm32 WASI must not expose wasm64 or LP64 macros\"\n"
    "#endif\n"
    "#if __STDC_HOSTED__ != 1\n"
    "#error \"WASI is a hosted C target\"\n"
    "#endif\n"
    "#if __SIZEOF_POINTER__ != 4 || __POINTER_WIDTH__ != 32 || __SIZEOF_LONG__ != 4 || __LONG_WIDTH__ != 32\n"
    "#error \"wasm32 WASI uses the ILP32 data model\"\n"
    "#endif\n"
    "#if __SIZEOF_LONG_LONG__ != 8 || __LONG_LONG_WIDTH__ != 64 || __SIZEOF_LONG_DOUBLE__ != 16 || __LONG_DOUBLE_WIDTH__ != 128\n"
    "#error \"unexpected wasm32 scalar data layout\"\n"
    "#endif\n"
    "#if !__is_target_arch(wasm32) || !__is_target_os(wasip1) || !__is_target_os(wasi)\n"
    "#error \"target condition builtins do not recognize WASI\"\n"
    "#endif\n"
    "\n"
    "_Static_assert(sizeof(void*) == 4, \"wasm32 pointers are 32-bit\");\n"
    "_Static_assert(sizeof(long) == 4, \"wasm32 long is 32-bit\");\n"
    "_Static_assert(sizeof(long long) == 8, \"wasm32 long long is 64-bit\");\n"
    "_Static_assert(sizeof(__INT64_TYPE__) == 8, \"__INT64_TYPE__ must remain 64-bit under ILP32\");\n"
    "_Static_assert(sizeof(__UINT64_TYPE__) == 8, \"__UINT64_TYPE__ must remain 64-bit under ILP32\");\n"
    "\n"
    "typedef struct WasiCiovec WasiCiovec;\n"
    "struct WasiCiovec\n"
    "{\n"
    "    const void* buffer;\n"
    "    unsigned int length;\n"
    "};\n"
    "\n"
    "extern unsigned short wasi_fd_write(unsigned int descriptor, const WasiCiovec* iovecs, unsigned int iovec_count,\n"
    "                                    unsigned int* bytes_written) __asm__(\"wasi_snapshot_preview1#fd_write\");\n"
    "// Deliberately declare an adapter-owned import too. The emitter must reuse\n"
    "// this function index rather than encode a duplicate proc_exit import.\n"
    "extern void wasi_proc_exit(unsigned int status) __asm__(\"wasi_snapshot_preview1#proc_exit\");\n"
    "\n"
    "static const char wasi_message[] = \"buster wasi ok\\n\";\n"
    "\n"
    "static void wasi_store_pointer(unsigned int* destination, const void* pointer)\n"
    "{\n"
    "    unsigned char* destination_bytes = (unsigned char*)destination;\n"
    "    const unsigned char* pointer_bytes = (const unsigned char*)&pointer;\n"
    "    destination_bytes[0] = pointer_bytes[0];\n"
    "    destination_bytes[1] = pointer_bytes[1];\n"
    "    destination_bytes[2] = pointer_bytes[2];\n"
    "    destination_bytes[3] = pointer_bytes[3];\n"
    "}\n"
    "\n"
    "int main(int argument_count, char** arguments, char** environment)\n"
    "{\n"
    "    unsigned int iovec_words[2];\n"
    "    wasi_store_pointer(&iovec_words[0], wasi_message);\n"
    "    iovec_words[1] = sizeof(wasi_message) - 1;\n"
    "    unsigned int bytes_written = 0;\n"
    "    unsigned short error = wasi_fd_write(1, (const WasiCiovec*)iovec_words, 1, &bytes_written);\n"
    "    if (error || bytes_written != iovec_words[1])\n"
    "    {\n"
    "        return 10;\n"
    "    }\n"
    "    if (argument_count < 2 || !arguments || !arguments[0] || !arguments[1] || arguments[1][0] != 'o' || arguments[1][1] != 'k' ||\n"
    "        arguments[1][2] != 0)\n"
    "    {\n"
    "        return 11;\n"
    "    }\n"
    "    if (!environment || !environment[0] || environment[0][0] != 'B')\n"
    "    {\n"
    "        return 12;\n"
    "    }\n"
    "    if (argument_count >= 3 && (!arguments[2] || arguments[2][70000] != 'x'))\n"
    "    {\n"
    "        return 13;\n"
    "    }\n"
    "    if (argument_count >= 3 && environment[0][70020] != 'y')\n"
    "    {\n"
    "        return 14;\n"
    "    }\n"
    "    return 0;\n"
    "}\n";

