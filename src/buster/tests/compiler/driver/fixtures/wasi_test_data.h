static char8 const compiler_driver_wasi_execution_script[] =
    "// Execute the emitted command in an independent Preview 1 runtime, including\n"
    "// a command whose argv and environment exceed the initial stack reserve.\n"
    "\"use strict\";\n"
    "\n"
    "const assert = require(\"node:assert/strict\");\n"
    "const fs = require(\"node:fs\");\n"
    "const {WASI} = require(\"node:wasi\");\n"
    "\n"
    "assert.equal(process.argv.length, 4, \"usage: node wasm_wasi_execution.js main.wasm start.wasm\");\n"
    "\n"
    "const mainModule = new WebAssembly.Module(fs.readFileSync(process.argv[2]));\n"
    "const imports = WebAssembly.Module.imports(mainModule);\n"
    "assert.equal(imports.filter(entry => entry.module === \"wasi_snapshot_preview1\" && entry.name === \"proc_exit\").length, 1);\n"
    "assert.ok(imports.some(entry => entry.module === \"wasi_snapshot_preview1\" && entry.name === \"fd_write\"));\n"
    "assert.ok(imports.every(entry => entry.module === \"wasi_snapshot_preview1\"));\n"
    "\n"
    "function run(module, args, env) {\n"
    "    const wasi = new WASI({version: \"preview1\", args, env, returnOnExit: true});\n"
    "    const instance = new WebAssembly.Instance(module, {wasi_snapshot_preview1: wasi.wasiImport});\n"
    "    assert.ok(instance.exports.memory instanceof WebAssembly.Memory);\n"
    "    assert.equal(wasi.start(instance), 0);\n"
    "    return instance.exports.memory.buffer.byteLength;\n"
    "}\n"
    "\n"
    "const initialBytes = run(mainModule, [\"app\", \"ok\"], {BUSTER_TEST: \"small\"});\n"
    "const largeBytes = run(mainModule, [\"app\", \"ok\", \"x\".repeat(90000)],\n"
    "                       {BUSTER_TEST: \"z\".repeat(70008) + \"y\"});\n"
    "assert.ok(largeBytes > initialBytes, \"WASI startup must grow memory for large arguments and environment\");\n"
    "\n"
    "const explicitStart = new WebAssembly.Module(fs.readFileSync(process.argv[3]));\n"
    "assert.equal(WebAssembly.Module.imports(explicitStart).length, 0);\n"
    "run(explicitStart, [\"app\"], {});\n"
    "\n"
    "console.log(\"3/3 wasm32 WASI Preview 1 command executions passed\");\n";

