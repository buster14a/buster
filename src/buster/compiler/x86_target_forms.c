static void x86_target_forms_scalar(const X86Target* target, uint8_t* allowed)
{
    const uint64_t available = target->features | BUSTER_X86_TARGET_KNOWN;
    for (uint32_t i = 0; i < X86_FORM_COUNT; i += 1)
    {
        const uint64_t required = x86_target_requirements[i];
        allowed[i] = required != 0 && (required & ~available) == 0;
    }
}

// Eight contiguous rows per iteration: no gathers, scratch allocation or speculative loads beyond the table.
static void x86_target_forms(const X86Target* target, uint8_t* allowed)
{
    const __m512i available = _mm512_set1_epi64((long long)(target->features | BUSTER_X86_TARGET_KNOWN));
    const __m512i zero = _mm512_setzero_si512();
    for (uint32_t i = 0; i < X86_FORM_COUNT; i += 8)
    {
        const uint32_t count = X86_FORM_COUNT - i < 8 ? X86_FORM_COUNT - i : 8;
        const __mmask8 active = (__mmask8)((1u << count) - 1);
        const __m512i required = _mm512_maskz_loadu_epi64(active, x86_target_requirements + i);
        const __mmask8 known = _mm512_cmpneq_epi64_mask(required, zero);
        const __mmask8 supported = known & _mm512_cmpeq_epi64_mask(_mm512_andnot_si512(available, required), zero);
        const __m512i flags = _mm512_maskz_set1_epi64(supported, 1);
        _mm_mask_storeu_epi8(allowed + i, active, _mm512_cvtepi64_epi8(flags));
    }
}

static bool x86_target_form_allowed(const uint8_t* allowed, uint32_t form)
{
    const uint32_t number = form & BUSTER_X86_FORM_NUMBER;
    const uint32_t row = number % X86_FORM_COUNT;
    return form <= UINT16_MAX && number < BUSTER_X86_FORM_TEMPLATES && allowed[row] != 0;
}

// Returns count on success or the first unsupported/invalid record. Empty input may have a null pointer.
static uint32_t x86_target_validate(const uint8_t* allowed, const X86Instruction* instructions, uint32_t count)
{
    uint32_t i = 0;
    while (i < count && x86_target_form_allowed(allowed, instructions[i].form) && x86_validate(instructions + i, 1) == 1)
    {
        i += 1;
    }
    return i;
}
