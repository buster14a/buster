// Original valid-C inputs with 100,000 pastes of two ASCII identifiers each. Repeated extern declarations are legal.
// The repeated case cycles through 256 names; the unique case inserts a different result on every invocation.
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>

static bool write_fixture(const char* directory, const char* name, bool unique)
{
    char path[4096];
    const int length = snprintf(path, sizeof(path), "%s/%s", directory, name);
    bool result = length >= 0 && (size_t)length < sizeof(path);
    FILE* output = result ? fopen(path, "w") : 0;
    result = output != 0;
    if (result)
    {
        fputs("/* Generated by pp-ablation/07-paste-ascii/generate_paste_fixture.c. */\n#define CAT(a,b) a ## b\n", output);
        for (uint32_t k = 0; k < 100000; k += 1)
        {
            fprintf(output, "extern int CAT(prefix_,name%u);\n", unique ? k : k % 256);
        }
        result = ferror(output) == 0;
        const int closed = fclose(output);
        result = result && closed == 0;
    }
    if (!result)
    {
        fprintf(stderr, "could not write %s/%s\n", directory, name);
    }
    return result;
}

int main(int argc, char** argv)
{
    bool result = argc == 2;
    if (result)
    {
        result = write_fixture(argv[1], "paste-repeated.c", false);
    }
    if (result)
    {
        result = write_fixture(argv[1], "paste-unique.c", true);
    }
    if (argc != 2)
    {
        fprintf(stderr, "usage: %s output-directory\n", argv[0]);
    }
    return result ? 0 : 1;
}
