// Creates independent C translation units for the three preprocessor hypotheses and a nested-argument control.
// The long unused arguments isolate collection; repeated literals amortize the definition's recipe construction;
// repeated expanded arguments emphasize substitution copying. None requires system headers or external predefines.

#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>

static bool write_fixture(const char* directory, const char* name, uint32_t shape)
{
    char path[4096];
    int length = snprintf(path, sizeof(path), "%s/%s", directory, name);
    bool result = length >= 0 && (size_t)length < sizeof(path);
    FILE* output = result ? fopen(path, "w") : 0;
    result = output != 0;
    if (result)
    {
        fputs("/* Generated by pp-ablation/generate_fixtures.c. */\n", output);
        if (shape < 2)
        {
            fputs("#define DROP(x) 0\n", output);
        }
        else if (shape == 2)
        {
            fputs("#define LITERAL(x) (x", output);
            for (uint32_t term = 0; term < 256; term += 1)
            {
                fputs(" + 1", output);
            }
            fputs(")\n", output);
        }
        else
        {
            fputs("#define REPEAT(x) (x), (x), (x), (x)\n", output);
        }
        fputs("static const int generated[] = {\n", output);
        uint32_t calls = shape == 3 ? 1024 : 4096;
        for (uint32_t call = 0; call < calls; call += 1)
        {
            if (shape == 2)
            {
                fputs("LITERAL(1),\n", output);
            }
            else
            {
                fputs(shape == 3 ? "REPEAT(" : "DROP(", output);
                if (shape == 1)
                {
                    fputc('(', output);
                }
                for (uint32_t term = 0; term < 256; term += 1)
                {
                    fprintf(output, "%u", term % 9 + 1);
                    if (term + 1 != 256)
                    {
                        fputs(" + ", output);
                    }
                    if (shape == 3 && term % 16 == 15)
                    {
                        fputc('\n', output);
                    }
                }
                if (shape == 1)
                {
                    fputc(')', output);
                }
                fputs("),\n", output);
            }
        }
        fputs("};\n", output);
        result = ferror(output) == 0;
        int closed = fclose(output);
        result = result && closed == 0;
    }
    if (!result)
    {
        fprintf(stderr, "could not write fixture %s/%s\n", directory, name);
    }
    return result;
}

int main(int argc, char** argv)
{
    bool result = argc == 2;
    if (result)
    {
        result = write_fixture(argv[1], "flat-unused.c", 0);
    }
    if (result)
    {
        result = write_fixture(argv[1], "nested-unused.c", 1);
    }
    if (result)
    {
        result = write_fixture(argv[1], "literal-runs.c", 2);
    }
    if (result)
    {
        result = write_fixture(argv[1], "argument-copies.c", 3);
    }
    if (argc != 2)
    {
        fprintf(stderr, "usage: %s output-directory\n", argv[0]);
    }
    return result ? 0 : 1;
}
