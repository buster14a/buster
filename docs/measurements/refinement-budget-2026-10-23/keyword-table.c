// Generates an exact 16-slot lookup for a first-party selection of predefined C names.
#include <inttypes.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>

int main(void)
{
    static const char* names[16] = {
        "int",
        "static",
        "return",
        "if",
        "const",
        "void",
        "char",
        "else",
        "case",
        "break",
        "struct",
        "unsigned",
        "sizeof",
        "typedef",
        "for",
        "while",
    };
    static const char* ids[16] = {
        "INT",
        "STATIC",
        "RETURN",
        "IF",
        "CONST",
        "VOID",
        "CHAR",
        "ELSE",
        "CASE",
        "BREAK",
        "STRUCT",
        "UNSIGNED",
        "SIZEOF",
        "TYPEDEF",
        "FOR",
        "WHILE",
    };
    uint64_t words[16] = { 0 };
    uint32_t slots[16] = { 0 };
    for (uint32_t i = 0; i < 16; i += 1)
    {
        memcpy(words + i, names[i], strlen(names[i]));
    }
    uint64_t state = 116;
    uint64_t multiplier = 0;
    uint64_t attempts = 0;
    for (; attempts < 100000000 && multiplier == 0; attempts += 1)
    {
        state ^= state >> 12;
        state ^= state << 25;
        state ^= state >> 27;
        const uint64_t candidate = state * UINT64_C(2685821657736338717) | 1;
        uint32_t used = 0;
        for (uint32_t i = 0; i < 16; i += 1)
        {
            const uint32_t slot = (uint32_t)((words[i] * candidate) >> 60);
            used |= 1u << slot;
            slots[slot] = i;
        }
        if (used == 65535)
        {
            multiplier = candidate;
        }
    }
    int result = 1;
    if (multiplier != 0)
    {
        printf("// Generated by keyword-table.c: seed 116, %" PRIu64 " attempts.\n", attempts);
        printf("#define BUSTER_REFINE_NAME_MULTIPLIER UINT64_C(0x%016" PRIx64 ")\n", multiplier);
        puts("static const uint64_t refine_name_words[16] = {");
        for (uint32_t i = 0; i < 16; i += 1)
        {
            printf("    UINT64_C(0x%016" PRIx64 "), // %s\n", words[slots[i]], names[slots[i]]);
        }
        puts("};\nstatic const uint32_t refine_name_ids[16] = {");
        for (uint32_t i = 0; i < 16; i += 1)
        {
            printf("    C_NAME_%s,\n", ids[slots[i]]);
        }
        puts("};");
        result = 0;
    }
    return result;
}
