#!/usr/bin/env python3
"""Generate four fixed independent chunk counts, never function dispatch."""
from pathlib import Path

parts = ["/* Generated by generate_unroll.py; do not hand edit. */\n"]
for unroll in (1, 2, 4, 8):
    body = [f'TARGET("avx512f") size_t overlap_avx512_{unroll}(const uint64_t *low, const uint64_t *high, size_t n)',
            '{', '    size_t result = n;', '    for (size_t j = 1; j < n && result == n; j += 1)',
            '    {', '        __m512i l = _mm512_set1_epi64((long long)low[j]);',
            '        __m512i h = _mm512_set1_epi64((long long)high[j]);', '        size_t i = 0;',
            f'        for (; j - i >= {unroll * 8}; i += {unroll * 8})', '        {']
    for k in range(unroll):
        body += [f'            __mmask8 a{k} = _mm512_cmp_epu64_mask(l, _mm512_loadu_si512(high + i + {k * 8}), _MM_CMPINT_LE);',
                 f'            __mmask8 b{k} = _mm512_cmp_epu64_mask(_mm512_loadu_si512(low + i + {k * 8}), h, _MM_CMPINT_LE);']
    terms = ' | '.join(f'(a{k} & b{k})' for k in range(unroll))
    body += [f'            if (({terms}) != 0)', '            {', '                result = j;', '                break;', '            }', '        }']
    if unroll > 1:
        body += ['        for (; j - i >= 8 && result == n; i += 8)', '        {',
                 '            __mmask8 a = _mm512_cmp_epu64_mask(l, _mm512_loadu_si512(high + i), _MM_CMPINT_LE);',
                 '            __mmask8 b = _mm512_cmp_epu64_mask(_mm512_loadu_si512(low + i), h, _MM_CMPINT_LE);',
                 '            if ((a & b) != 0) result = j;', '        }']
    body += ['        for (; i < j && result == n; i += 1)', '        {',
             '            if (low[j] <= high[i] && low[i] <= high[j]) result = j;',
             '        }', '    }', '    return result;', '}', '']
    parts.append('\n'.join(body))
Path(__file__).with_name('unroll.inc').write_text('\n'.join(parts))
